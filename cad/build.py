"""Build the Strider CAD: meshes for the MJCF, mass properties, and a posed STEP assembly (ADR 0003).

    python -m cad.build            # writes build/meshes/*.stl, spec/massprops.yaml, build/cad/strider_home.step

spec/massprops.yaml is committed (reviewed like a fixture); tests check it matches a fresh CAD build.
"""
from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import numpy as np
import yaml
from build123d import Compound, Location, export_step, export_stl

from cad.massprops import MassProps, solid_props, volume
from cad.parts import PartSpec, all_bodies
from model.spec import MASSPROPS_PATH, REPO_ROOT, load_spec

MESH_DIR = REPO_ROOT / "build" / "meshes"
CAD_DIR = REPO_ROOT / "build" / "cad"
# STL tessellation: fine enough that curved parts render smooth (no visible facets).
LINEAR_TOL = 0.08e-3
ANGULAR_TOL = 0.08


def mesh_key(body: str) -> str:
    """Thighs and calves are identical on every leg, so they share one set of meshes."""
    for kind in ("thigh", "calf"):
        if body.endswith(f"_{kind}"):
            return kind
    return body


def part_density(p: PartSpec, spec: dict[str, Any]) -> float:
    if p.mass is not None:
        return p.mass / volume(p.shape)
    return float(spec["materials"][p.material])


def compute_massprops(bodies: dict[str, list[PartSpec]], spec: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for body, parts in bodies.items():
        total: MassProps | None = None
        rows = {}
        for p in parts:
            mp = solid_props(p.shape, part_density(p, spec))
            rows[p.name] = round(float(mp.mass), 6)
            total = mp if total is None else total + mp
        assert total is not None
        I = total.inertia
        out[body] = {
            "mass": round(float(total.mass), 6),
            "com": [round(float(v), 7) for v in total.com],
            # MuJoCo fullinertia order: ixx iyy izz ixy ixz iyz (about the COM, body axes)
            "fullinertia": [float(f"{v:.6e}") for v in (I[0, 0], I[1, 1], I[2, 2], I[0, 1], I[0, 2], I[1, 2])],
            "parts": rows,
        }
    out["_total_mass"] = round(sum(v["mass"] for k, v in out.items() if not k.startswith("_")), 6)
    return out


def export_meshes(bodies: dict[str, list[PartSpec]], out: Path = MESH_DIR) -> None:
    out.mkdir(parents=True, exist_ok=True)
    done = set()
    for body, parts in bodies.items():
        key = mesh_key(body)
        if key in done:
            continue
        done.add(key)
        for p in parts:
            export_stl(p.visual if p.visual is not None else p.shape, str(out / f"{key}__{p.name}.stl"), tolerance=LINEAR_TOL,
                       angular_tolerance=ANGULAR_TOL)


def export_posed_step(bodies: dict[str, list[PartSpec]], poses: dict[str, tuple[np.ndarray, np.ndarray]],
                      path: Path) -> None:
    """poses: body -> (world position, world rotation matrix)."""
    shapes = []
    for body, parts in bodies.items():
        pos, rot = poses[body]
        loc = Location(_transform(pos, rot))
        for p in parts:
            s = p.shape.moved(loc)
            s.label = f"{body}/{p.name}"
            shapes.append(s)
    path.parent.mkdir(parents=True, exist_ok=True)
    export_step(Compound(children=shapes), str(path))


def _transform(pos: np.ndarray, rot: np.ndarray):
    from OCP.gp import gp_Trsf
    t = gp_Trsf()
    t.SetValues(*rot[0], pos[0], *rot[1], pos[1], *rot[2], pos[2])
    return t


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--no-step", action="store_true")
    args = ap.parse_args()
    spec = load_spec()
    bodies = all_bodies(spec)
    mp = compute_massprops(bodies, spec)
    MASSPROPS_PATH.write_text("# GENERATED by `python -m cad.build` from the CAD solids (ADR 0003). Do not edit.\n"
                              + yaml.safe_dump(mp, sort_keys=False))
    export_meshes(bodies)
    print(f"total mass {mp['_total_mass']:.3f} kg (budget {spec['budget']['total_mass']} kg)")
    if not args.no_step:
        from model.build import home_body_poses
        export_posed_step(bodies, home_body_poses(), CAD_DIR / "strider_home.step")
        print(f"wrote {CAD_DIR / 'strider_home.step'}")


if __name__ == "__main__":
    main()
